// Quita permisos solo del build de release: escribe android/app/src/release/AndroidManifest.xml con
// tools:node="remove". Ese manifiesto tiene prioridad sobre src/main y sobre los de las librerías
// (INTERNET y almacenamiento también vienen de expo-file-system; ACCESS_NETWORK_STATE de expo-image).
// El debug no cambia: necesita INTERNET para Metro y SYSTEM_ALERT_WINDOW para el menú de desarrollo.
// No se usa android.blockedPermissions de app.json porque aplica a todas las variantes.
const fs = require("fs");
const path = require("path");
const { withDangerousMod } = require("expo/config-plugins");

const REMOVED = [
  "android.permission.INTERNET",
  "android.permission.ACCESS_NETWORK_STATE",
  "android.permission.SYSTEM_ALERT_WINDOW",
  "android.permission.VIBRATE",
  "android.permission.READ_EXTERNAL_STORAGE",
  "android.permission.WRITE_EXTERNAL_STORAGE",
];

const MANIFEST = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withReleasePermissions.js: do not edit, prebuild rewrites it. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
          xmlns:tools="http://schemas.android.com/tools">
${REMOVED.map((name) => `  <uses-permission android:name="${name}" tools:node="remove"/>`).join("\n")}
</manifest>
`;

module.exports = function withReleasePermissions(config) {
  return withDangerousMod(config, [
    "android",
    async (config) => {
      const dir = path.join(config.modRequest.platformProjectRoot, "app", "src", "release");
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, "AndroidManifest.xml"), MANIFEST);
      return config;
    },
  ]);
};
